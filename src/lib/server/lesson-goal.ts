/** Rules for formulating the lesson goal. The lesson type shapes the goal internally but is never printed. */
const TYPE_RESULTS: Array<[RegExp, string]> = [
  [/контрол|оценивани|проверочн/i, "что ученики смогут самостоятельно продемонстрировать и проверить в освоенном материале"],
  [/коррекц|анализ результат/i, "какие затруднения ученики смогут выявить и исправить и каким способом будут действовать после коррекции"],
  [/систематиз|обобщ|повторени/i, "что ученики смогут связать в систему, сравнить, классифицировать или обобщить"],
  [/закреп|применени|отработ|развивающ|практик/i, "какое известное знание или способ действия ученики научатся применять увереннее, точнее или в новых ситуациях"],
  [/комбинир/i, "какой главный результат является новым или наиболее значимым для ученика"],
  [/открыти|нового|освоени/i, "какое новое знание, правило, способ действия или связь ученики откроют и смогут использовать"],
];

export function goalResultFocus(lessonType: string): string {
  return TYPE_RESULTS.find(([pattern]) => pattern.test(lessonType))?.[1] ?? TYPE_RESULTS[4]![1];
}

export function buildLessonGoalRules(lessonType: string): string {
  return `ПРАВИЛА ФОРМУЛИРОВКИ ЦЕЛИ УРОКА:
- Цель показывает, что изменится в знаниях, действиях и понимании учеников к концу урока, а не «пройти тему».
- Пиши от результата для ученика: что он сможет сделать, объяснить, показать, применить, сравнить, обосновать, построить, классифицировать, проверить или сформулировать к концу урока.
- Цель отражает конкретный содержательный результат по теме, а не деятельность учителя и не процесс прохождения материала.
- Связывай цель с предметом, возрастом учеников и темой. Для этого урока главный акцент результата: ${goalResultFocus(lessonType)}.
- Учебный продукт (алгоритм, правило, модель, таблица, решение, объяснение) указывай только если он естественно следует из содержания урока. Схемы не упоминай.
- Формулируй результат так, чтобы в конце урока можно было проверить, достигнута цель или нет.
- Избегай туманных формулировок: «повысить интерес», «развить мышление», «сформировать представление» без конкретного результата.
- Не повторяй только название темы другими словами. Не включай этапы урока, действия учителя, перечень заданий или сценарий.
- Формат: одна связная формулировка из 2–4 предложений, без нумерации, HTML и конструкций «сначала… потом…».
- Тип урока используй только для выбора акцента; само название типа урока нигде не пиши.`;
}
